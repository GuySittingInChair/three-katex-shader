// Where a thing on screen comes from. Every galaxy layer and every event carries one of these, and the interface
// shows it, so a made-up explosion is never mistaken for a real one.

export const PROVENANCE = {
  OBSERVED: { label: 'Observed', col: '#7dffc0', means: 'An actual astronomical observation.' },
  SIMULATED: { label: 'Simulated', col: '#9db4ff', means: 'Taken from a published numerical simulation.' },
  INFERRED: { label: 'Inferred', col: '#ffd27a', means: 'Worked out from measurements using a scientific model.' },
  PROCEDURAL: { label: 'Procedural', col: '#ff9f5a', means: 'Generated by this page from scientifically informed odds. Not a real event.' },
  ARTISTIC: { label: 'Artistic', col: '#d8a8ff', means: 'Illustration only: how it is drawn, not something measured.' },
};

export const isProvenance = (k) => Object.prototype.hasOwnProperty.call(PROVENANCE, k);

/** "INFERRED: text" → { kind: 'INFERRED', text } (the data files store provenance notes this way) */
export function parseProvenance(note) {
  const m = /^([A-Z]+):\s*(.*)$/s.exec(String(note));
  if (!m || !isProvenance(m[1])) throw new Error(`bad provenance note: ${note}`);
  return { kind: m[1], text: m[2] };
}

/** a small coloured label for HTML */
export function badge(kind) {
  const p = PROVENANCE[kind];
  if (!p) throw new Error(`unknown provenance ${kind}`);
  return `<span class="gx-badge" title="${p.means}" style="color:${p.col};border-color:${p.col}66">${p.label}</span>`;
}
